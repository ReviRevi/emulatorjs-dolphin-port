#!/usr/bin/env python3
# Generates Source/Core/VideoBackends/WebGPU/WGPUEmbedded.inc from WGPURuntime.js and the naga-wasm
# npm package (naga GLSL->WGSL translator). Usage: gen_wgpu_embed.py <dolphin src> <naga-wasm package dir>
import base64, re, sys
src, pkg = sys.argv[1], sys.argv[2]
d = src + '/Source/Core/VideoBackends/WebGPU/'
rt = open(d + 'WGPURuntime.js').read()
g = open(pkg + '/dist/wasm/naga.js').read()
g = re.sub(r'^export (class|function) ', r'\1 ', g, flags=re.M).replace('export { initSync, __wbg_init as default };', '').replace('import.meta.url', "''")
b = base64.b64encode(open(pkg + '/dist/wasm/naga_bg.wasm', 'rb').read()).decode()
assert ')WGPUJS"' not in rt + g
with open(d + 'WGPUEmbedded.inc', 'w') as f:
    f.write('// Generated by gen_wgpu_embed.py - do not edit\n')
    f.write('static const char kWgpuRuntime[] = R"WGPUJS(' + rt + ')WGPUJS";\n')
    f.write('static const char kNagaGlue[] = R"WGPUJS(' + g + ')WGPUJS";\n')
    f.write('static const char kNagaWasmB64[] =\n')
    for i in range(0, len(b), 4096):
        f.write('"' + b[i:i+4096] + '"\n')
    f.write(';\n')
print('wrote', d + 'WGPUEmbedded.inc')
